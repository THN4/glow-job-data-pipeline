-- Reviewed relationships between canonical skills, grounded in document sources.
-- Learning modules and application tables are outside this migration.
CREATE TABLE knowledge.skill_dependencies (
    dependency_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prerequisite_skill_id bigint NOT NULL REFERENCES core.skills (skill_id),
    target_skill_id bigint NOT NULL REFERENCES core.skills (skill_id),
    dependency_type text NOT NULL
        CHECK (dependency_type IN ('prerequisite', 'recommended_before', 'related')),
    strength text NOT NULL
        CHECK (strength IN ('required', 'strong', 'recommended', 'weak')),
    confidence numeric(4, 3) CHECK (confidence BETWEEN 0 AND 1),
    source_id bigint REFERENCES knowledge.knowledge_sources (source_id),
    evidence_text text,
    is_verified boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_skill_dependencies_distinct_skills
        CHECK (prerequisite_skill_id <> target_skill_id),
    CONSTRAINT ck_skill_dependencies_verified_evidence
        CHECK (NOT is_verified OR (
            source_id IS NOT NULL
            AND evidence_text IS NOT NULL
            AND length(btrim(evidence_text)) > 0
        )),
    CONSTRAINT uq_skill_dependencies_edge
        UNIQUE (prerequisite_skill_id, target_skill_id, dependency_type)
);

CREATE INDEX ix_skill_dependencies_verified_target
    ON knowledge.skill_dependencies (target_skill_id)
    WHERE is_verified;

CREATE INDEX ix_skill_dependencies_prerequisite
    ON knowledge.skill_dependencies (prerequisite_skill_id);
