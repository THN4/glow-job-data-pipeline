-- Store reviewed document sources and their retrievable text chunks.
-- Embeddings use Gemini Embedding 2 with 768 output dimensions for the demo.
CREATE SCHEMA IF NOT EXISTS knowledge;

CREATE TABLE knowledge.knowledge_sources (
    source_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id bigint REFERENCES core.skills (skill_id),
    source_type text NOT NULL,
    title text NOT NULL,
    source_url text,
    storage_key text,
    publisher text,
    is_active boolean NOT NULL DEFAULT true,
    collected_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE knowledge.knowledge_chunks (
    chunk_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES knowledge.knowledge_sources (source_id),
    skill_id bigint REFERENCES core.skills (skill_id),
    topic text,
    chunk_index integer NOT NULL,
    content text NOT NULL,
    metadata jsonb,
    embedding_model text,
    embedding vector(768),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_knowledge_chunks_source_index UNIQUE (source_id, chunk_index)
);
