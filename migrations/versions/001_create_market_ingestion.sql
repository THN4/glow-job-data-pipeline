CREATE SCHEMA IF NOT EXISTS core;
CREATE SCHEMA IF NOT EXISTS market;
CREATE SCHEMA IF NOT EXISTS system;

CREATE TABLE core.companies (
    company_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name text NOT NULL,
    normalized_name text,
    company_website text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_companies_normalized_name
    ON core.companies (normalized_name);

CREATE TABLE core.careers (
    career_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    career_name text NOT NULL,
    description text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE core.career_profiles (
    career_profile_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    career_id bigint NOT NULL REFERENCES core.careers (career_id),
    slug text NOT NULL UNIQUE,
    profile_name text NOT NULL,
    seniority_level text NOT NULL,
    description text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_career_profiles_career_id
    ON core.career_profiles (career_id);

CREATE TABLE system.ingestion_runs (
    run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_key text UNIQUE,
    source text NOT NULL,
    career_profile_id bigint REFERENCES core.career_profiles (career_profile_id),
    raw_storage_key text,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    jobs_fetched integer NOT NULL DEFAULT 0 CHECK (jobs_fetched >= 0),
    jobs_inserted integer NOT NULL DEFAULT 0 CHECK (jobs_inserted >= 0),
    jobs_updated integer NOT NULL DEFAULT 0 CHECK (jobs_updated >= 0),
    jobs_failed integer NOT NULL DEFAULT 0 CHECK (jobs_failed >= 0),
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'running', 'completed', 'failed')),
    error_message text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE market.job_postings (
    job_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_job_id text,
    company_id bigint REFERENCES core.companies (company_id),
    career_profile_id bigint NOT NULL REFERENCES core.career_profiles (career_profile_id),
    job_title text NOT NULL,
    normalized_job_title text,
    job_description text,
    location text,
    city text,
    state text,
    country char(2),
    employment_type text,
    provider text NOT NULL DEFAULT 'jsearch',
    publisher text,
    source_url text,
    posted_at timestamptz,
    collected_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_job_postings_provider_job UNIQUE (provider, provider_job_id)
);

CREATE INDEX ix_job_postings_career_profile_id
    ON market.job_postings (career_profile_id);
CREATE INDEX ix_job_postings_company_id
    ON market.job_postings (company_id);
CREATE INDEX ix_job_postings_posted_at
    ON market.job_postings (posted_at);

CREATE TABLE market.job_search_matches (
    job_id bigint NOT NULL REFERENCES market.job_postings (job_id),
    run_id bigint NOT NULL REFERENCES system.ingestion_runs (run_id),
    career_profile_id bigint NOT NULL REFERENCES core.career_profiles (career_profile_id),
    search_query text NOT NULL,
    collected_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (job_id, run_id, search_query)
);

CREATE INDEX ix_job_search_matches_run_id
    ON market.job_search_matches (run_id);
