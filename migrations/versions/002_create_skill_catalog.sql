CREATE TABLE core.skills (
    skill_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name text NOT NULL UNIQUE,
    skill_category text,
    description text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_skills_name_lower
    ON core.skills (lower(skill_name));

CREATE TABLE core.skill_aliases (
    alias_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id bigint NOT NULL REFERENCES core.skills (skill_id),
    alias text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_skill_aliases_alias_lower
    ON core.skill_aliases (lower(alias));
